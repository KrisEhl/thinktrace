import type { Claim, GlassboxEvent, Source } from "../api/types";
import type { RunState } from "../state/reducer";
import { children, nodeConfidence } from "../state/selectors";
import type { Step } from "./fixture";

// Mock-only helpers: a tiny "researcher" that grows a branch with a traceable (but invented) claim, and a reply
// composer that answers chat questions from the claims already in the graph.

let seq = 1;
const hash = (s: string) => [...s].reduce((a, c) => (a * 31 + c.charCodeAt(0)) >>> 0, 7);
const confFor = (n: number) => (n >= 3 ? 0.9 : n === 2 ? 0.75 : n === 1 ? 0.5 : 0);

const VERDICT_LINES = [
  "reports are mixed but lean positive",
  "most sources agree this is a manageable risk",
  "figures differ by vendor and need local validation",
  "evidence is thin and mostly vendor-supplied",
];

export interface Research {
  steps: Step[];
  node_id: string;
  claim_ids: string[];
}

/** Grow a branch under `parent_id`: search, read 1-3 sources, one claim each, then stop. Deterministic per topic. */
export function research(parent_id: string, label: string, topic: string, origins?: number): Research {
  const n = seq++;
  const nid = `x${n}`;
  const k = origins ?? 1 + (hash(topic) % 3);
  const line = VERDICT_LINES[hash(topic) % VERDICT_LINES.length];
  const steps: Step[] = [];
  const claim_ids: string[] = [];
  const at = (ms: number, e: GlassboxEvent) => steps.push([ms, e]);
  const dec = (action: "search" | "read" | "stop", why: string, extra: object = {}) =>
    at(350, { type: "decision", decision: { id: `decx${n}-${steps.length}`, node_id: nid, action, why, ts: Date.now(), ...extra } });

  at(300, { type: "direction_created", node: { id: nid, kind: "direction", parent_id, label: label.slice(0, 30), status: "running", traffic: 0 } });
  dec("search", `Asked about this directly: search for "${topic}".`, { query: topic });
  const originIds: string[] = [];
  for (let i = 0; i < k; i++) {
    const origin = `o-x${n}-${i}`;
    originIds.push(origin);
    const finding = `Regarding ${topic}, ${line}.`;
    const s: Source = {
      id: `sx${n}-${i}`,
      origin_id: origin,
      domain: `sim-source-${i + 1}.example`,
      title: `Simulated source ${i + 1} on ${label}`,
      url: `https://sim-source-${i + 1}.example/${n}`,
      origin: "web",
      text: `Simulated page ${i + 1}. This text is generated by the mock backend. ${finding} Please treat as an illustration only.`,
    };
    const quote = finding;
    const idx = s.text.indexOf(quote);
    const cid = `cx${n}-${i}`;
    claim_ids.push(cid);
    if (i > 0) dec("search", `${i} origin${i > 1 ? "s" : ""} so far. Look for another independent source.`, { query: `${topic} independent` });
    else dec("read", "Read the top result.", { source_id: s.id });
    at(350, { type: "source_added", source: s });
    const claim: Claim = { id: cid, node_id: nid, source_id: s.id, text: finding, quote, verified: null, span: null, confidence: 0, origin_ids: [...originIds] };
    at(250, { type: "claim_added", claim });
    at(250, { type: "claim_verified", claim_id: cid, verified: true, span: [idx, idx + quote.length] });
    at(200, { type: "confidence_changed", claim_id: cid, confidence: confFor(originIds.length), origin_ids: [...originIds] });
  }
  dec("stop", k >= 3 ? "Three independent origins." : "Budget used for a side question.", {});
  at(200, { type: "confidence_changed", node_id: nid, confidence: confFor(k) });
  at(150, { type: "verdict_set", node_id: nid, verdict: k >= 2 ? "yes" : "uncertain" });
  at(100, { type: "direction_stopped", node_id: nid, reason: "Side question answered in the mock." });
  return { steps, node_id: nid, claim_ids };
}

const STOP = new Set("what about does this that with from have there their which would could should into your more than they them then when where while whether also been being were will just only some such like very much many ask tell give show".split(" "));
const tokens = (s: string) => s.toLowerCase().replace(/[^a-z0-9 ]/g, " ").split(/\s+/).filter((w) => w.length > 3 && !STOP.has(w));

const subtreeIds = (st: RunState, id: string): string[] => [id, ...children(st, id).flatMap((c) => subtreeIds(st, c.id))];

export interface Reply {
  text: string;
  claim_ids: string[];
  /** true when nothing relevant was found and a branch should be researched. */
  branch: boolean;
}

export function compose(st: RunState, node_id: string, question: string): Reply {
  const q = question.toLowerCase();
  const live = Object.values(st.claims).filter((c) => c.verified && st.nodes[c.node_id]?.status !== "deactivated");

  if (/summar|overview|tl;?dr|recap/.test(q)) {
    const cited = st.answer.filter((s) => s.claim_ids.length);
    return { text: cited.length ? cited.map((s) => s.text).join(" ") : "There is no answer to summarise yet.", claim_ids: cited.flatMap((s) => s.claim_ids), branch: false };
  }
  if (/confiden|how sure|certain|weak|uncertain/.test(q)) {
    const dirs = Object.values(st.nodes).filter((n) => n.kind === "direction" && n.status !== "deactivated" && nodeConfidence(st, n.id) !== undefined);
    const weakest = dirs.sort((a, b) => (nodeConfidence(st, a.id) ?? 0) - (nodeConfidence(st, b.id) ?? 0)).slice(0, 3);
    return {
      text: weakest.length ? `Weakest spots: ${weakest.map((n) => `${n.label} (${(nodeConfidence(st, n.id) ?? 0).toFixed(2)})`).join(", ")}. Select one and press Dig deeper.` : "Nothing has a confidence yet.",
      claim_ids: [],
      branch: false,
    };
  }
  if (/source|evidence|origin|cited|used/.test(q)) {
    const origins = new Set(Object.values(st.sources).map((s) => s.origin_id)).size;
    const used = live.filter((c) => st.answer.some((s) => s.claim_ids.includes(c.id))).length;
    return { text: `${Object.keys(st.sources).length} sources from ${origins} independent origins. ${used} of ${Object.keys(st.claims).length} claims feed the answer; the rest are unverified, deactivated or not cited. See the Ledger tab.`, claim_ids: [], branch: false };
  }

  const scope = new Set(subtreeIds(st, node_id));
  const qt = tokens(question);
  const scored = live
    .filter((c) => scope.has(c.node_id) || node_id === "q")
    .map((c) => ({ c, score: qt.filter((t) => (c.text + " " + (st.nodes[c.node_id]?.label ?? "")).toLowerCase().includes(t)).length }))
    .filter((x) => x.score > 0)
    .sort((a, b) => b.score - a.score || b.c.confidence - a.c.confidence)
    .slice(0, 2);

  const wantsMore = /dig|look into|research|find|search|investigate/.test(q);
  if (scored.length) {
    const nodeLabel = st.nodes[scored[0].c.node_id]?.label ?? "this";
    const conf = nodeConfidence(st, scored[0].c.node_id);
    const needs = st.needs_human[scored[0].c.node_id];
    return {
      text: `On “${nodeLabel}”: ${scored.map((x) => x.c.text.replace(/\.$/, "")).join("; ")}.${conf !== undefined ? ` Confidence there is ${conf.toFixed(2)}.` : ""}${needs ? ` Note, it needs you: ${needs}` : ""}${wantsMore ? " I am opening a branch to look further." : ""}`,
      claim_ids: scored.map((x) => x.c.id),
      branch: wantsMore,
    };
  }
  return { text: `I have nothing on that in the graph yet, so I am opening a branch under “${st.nodes[node_id]?.label ?? "the question"}” to research it.`, claim_ids: [], branch: true };
}

export const labelFrom = (text: string) => {
  const w = text.replace(/[?!.]/g, "").split(/\s+/).filter(Boolean).slice(0, 4).join(" ");
  return w.charAt(0).toUpperCase() + w.slice(1);
};
